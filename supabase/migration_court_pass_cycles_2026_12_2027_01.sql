--
-- Brian, 2026-11-03: the XP unit is pickleballs; 30 tiers and 1,360 XP, as
-- Doggle's Park Pass; the premium lane is "Premium track coming soon", never
-- sold. Later the same day: Court Pass launches with November (back-dated to
-- Nov 1), December keeps these winter items, and there is no daily pickleball
-- cap. Spec: docs/court-pass.md (Server §3). Port of Doggle 0499.
--
--   * cycles   '2026-12' Dec 1 2026 to Jan 1 2027, '2027-01' to Feb 1 2027,
--              each at Pacific midnight, computed with at time zone (all
--              three are 08:00Z, PST). daily_xp_cap null: no daily cap (as
--              Doggle 0501). December: premium coming soon. January: premium 'off'.
--   * tiers    30 per cycle, cumulative: tier 1 = 10, tiers 2-5 +25 each,
--              tiers 6-30 +50 each. Tier 5 = 110, tier 15 = 610, tier 30 = 1,360.
--   * free     every tier pays. Plain tiers pay pickles as a gold row (no XP,
--              outside the play cap): 40 (tiers 1-4), 60 (6-14), 80 (16-24),
--              100 (26-29). December: winter items at 5, 10, 15 (rare), 20,
--              25 and 30 (rare, the finale): 1,680 pickles plus 6 items.
--              January: 150 at 5, 10, 15, 20, 25 and 250 at 30: 2,680 pickles.
--              (The spec's 1,820 / 2,820 totals were off by 140; the per-tier
--              amounts above are the spec's and are what this seeds.)
--   * premium  December's 6 items, display only: rare at 5-25, legendary at
--              30. Nothing grants (the payout pays the free lane only) or sells
--              them. January has none.
--   * items    December's 12, the winter court theme:
--              4 shop_items (2 avatars, 2 name styles): cost 0, is_active
--                false, so the Shop never lists them and purchase_shop_item /
--                gift_shop_item refuse them; equip_shop_item takes the cost-0
--                purchase row the payout writes. sort_order 900-903.
--              8 home_items (My Place decor): cost 0, track_only, not starters,
--                season '2026-12', available_until = a month before the
--                cycle's start (Nov 1, read from the cycle row, already past),
--                so app builds from before this hide them from non-owners and
--                buy_home_item refuses them with the tier that pays them. The
--                art (home_item_art and the imported art_aspect) is
--                migration_court_pass_art_2026_12.sql, generated by
--                art/court-pass/build.mjs; until it runs the app draws the
--                dashed placeholder.
--
-- Order matters: cycles, items, tiers, rewards (rewards point at all three).
-- daily_xp_cap is null (no cap): the column has no default, so it is spelled
-- out here; the copy test (courtPassCopy.test.ts) reads it.
-- Re-running changes nothing: catalog rows are ON CONFLICT DO NOTHING, and
-- the items' "not in the shop" guard (Shop: inactive, cost 0; My Place:
-- track_only, cost 0, not a starter, an available_until no later than the
-- seed's) is re-asserted on conflict, so a row that already existed can't
-- stay buyable. The persona test re-runs this file (T8).
--
-- Locks: row inserts on the track tables, shop_items and home_items only.
-- Idempotent; no top-level transaction. Apply in ONE transaction with
-- migration_court_pass_xp.sql, migration_court_pass_cycles_2026_11.sql and
-- court_pass_catchup_2026_11.sql (court-pass-apply.ps1).
-- Persona test: supabase/tests/court_pass_personas.sql
--   (node supabase/tests/build-court-pass-test.mjs <out.sql>).
-- ============================================================

do $$
begin
  if to_regclass('public.reward_track_cycles') is null
     or not exists (select 1 from information_schema.columns
                     where table_schema = 'public' and table_name = 'home_items' and column_name = 'track_only')
     or to_regprocedure('public.get_reward_track(text)') is null
     or to_regprocedure('public._pl_track_settle(uuid)') is null then
    raise exception 'migration_court_pass_cycles_2026_12_2027_01.sql needs migration_court_pass_tables.sql and migration_court_pass_xp.sql applied first';
  end if;
end $$;


