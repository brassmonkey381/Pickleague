-- Pickles on every free tier still empty: December's plain tiers, all of
-- January. 40 (tiers 1-4), 60 (6-14), 80 (16-24), 100 (26-29), 150 at
-- January's fifth tiers, 250 at tier 30. rarity stays null for pickles.
insert into public.reward_track_rewards (cycle_id, tier, lane, kind, amount, shop_item_slug, home_item_id, title, rarity)
select t.cycle_id, t.tier, 'free', 'pickles', p.amount, null, null, p.amount || ' pickles', null
  from public.reward_track_tiers t
 cross join lateral (select case when t.tier = 30     then 250
                                 when t.tier % 5 = 0  then 150
                                 when t.tier < 5      then 40
                                 when t.tier < 15     then 60
                                 when t.tier < 25     then 80
                                 else 100 end as amount) p
 where t.cycle_id in ('2026-12', '2027-01')
   and not exists (select 1 from public.reward_track_rewards r
                    where r.cycle_id = t.cycle_id and r.tier = t.tier and r.lane = 'free')
on conflict (cycle_id, tier, lane) do nothing;

