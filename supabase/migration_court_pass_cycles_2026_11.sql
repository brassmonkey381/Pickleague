--              daily_xp_cap null: no daily cap (as Doggle 0501).
--   * tiers    December's curve: 30 tiers, tier 1 = 10, tiers 2-5 +25 each,
--              tiers 6-30 +50 each. Tier 5 = 110, tier 15 = 610, tier 30 = 1,360.
--   * free     every tier pays, with December's amounts: pickles as a gold row
