--              60 (6-14), 80 (16-24), 100 (26-29); harvest items at 5, 10, 15
--              (rare), 20, 25 and 30 (rare, the finale): 1,680 pickles plus 6
--              items.
--   * premium  6 items, display only: rare at 5-25, legendary at 30. Nothing
--              grants (the payout pays the free lane only) or sells them.
--   * items    the 12 in art/court-pass/2026-11/catalog.json, exactly:
--              4 shop_items (2 avatars, 2 name styles): cost 0, is_active
--                false, so the Shop never lists them and purchase_shop_item /
--                gift_shop_item refuse them; equip_shop_item takes the cost-0
--                purchase row the payout writes. The description is the
--                catalog's. sort_order 890-893 (December's are 900-903).
--                Golden Harvest reuses the existing sparkle name effect.
--              8 home_items (My Place decor): cost 0, track_only, not starters,
--                season '2026-11', available_until = a month before the
--                cycle's start (Oct 1, read from the cycle row, already past),
--                so app builds from before this hide them from non-owners and
--                buy_home_item refuses them with the tier that pays them.
--                sort 890-897. home_items has no description column, so the
--                catalog's lines for them are not stored. The art
--                (home_item_art and the imported art_aspect) is
--                migration_court_pass_art_2026_11.sql, generated by
--                node art/court-pass/build.mjs 2026-11.
--
-- Order matters: cycles, items, tiers, rewards (rewards point at all three).
-- Re-running changes nothing: catalog rows are ON CONFLICT DO NOTHING, and
-- the items' "not in the shop" guard (Shop: inactive, cost 0; My Place:
-- track_only, cost 0, not a starter, an available_until no later than the
-- seed's) is re-asserted on conflict, so a row that already existed can't
-- stay buyable. The persona test re-runs this file (T8).
--
-- Locks: row inserts on the track tables, shop_items and home_items only.
-- Idempotent; no top-level transaction. Apply in ONE transaction with
-- migration_court_pass_xp.sql, migration_court_pass_cycles_2026_12_2027_01.sql
-- and court_pass_catchup_2026_11.sql (court-pass-apply.ps1): the catch-up
-- replays every pickle_ledger row since this cycle's start.
-- Persona test: supabase/tests/court_pass_personas.sql
--   (node supabase/tests/build-court-pass-test.mjs <out.sql>).
-- ============================================================

do $$
begin
  if to_regclass('public.reward_track_cycles') is null
     or not exists (select 1 from information_schema.columns
                     where table_schema = 'public' and table_name = 'home_items' and column_name = 'track_only')
     or to_regprocedure('public.get_reward_track(text)') is null
     or to_regprocedure('public._pl_track_settle(uuid)') is null then
    raise exception 'migration_court_pass_cycles_2026_11.sql needs migration_court_pass_tables.sql and migration_court_pass_xp.sql applied first';
  end if;
end $$;


