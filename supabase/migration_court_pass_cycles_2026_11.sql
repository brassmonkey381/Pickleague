-- ════ 3. Tiers (December's curve) ════════════════════════════════════════
insert into public.reward_track_tiers (cycle_id, tier, xp_required)
select c.id, t,
       case when t = 1 then 10
            when t <= 5 then 10 + 25 * (t - 1)           -- 35, 60, 85, 110
            else 110 + 50 * (t - 5) end                  -- 160 .. 1,360
  from public.reward_track_cycles c
 cross join generate_series(1, 30) as t
 where c.id = '2026-11'
on conflict (cycle_id, tier) do nothing;


