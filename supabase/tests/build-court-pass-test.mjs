#!/usr/bin/env node
// Build the Court Pass persona test: ONE SQL file that is
//
//   begin;
//   set local lock_timeout = '10s';                     a blocked lock fails in 10 s (rolls back)
//   set local check_function_bodies = off;
//   lock table public.profiles in exclusive mode;       (not with --applied; see below)
//   <court_pass_personas.sql up to -- @@MIGRATIONS@@>   harness, helpers, the launch persona's November rows
//   <MIGRATIONS, below>                                 tables, xp, both cycles files, the catch-up, the art
//   <court_pass_personas.sql up to -- @@RERUN@@>        the seed and catch-up checks, test cycles, personas, every earn
//   <MIGRATIONS> again                                  (re-runnable: must change nothing; the catch-up skips itself)
//   <migration_rls_hardening_2026q3.sql>                (the RPCs must stay callable)
//   <the rest of court_pass_personas.sql>               assertions, then the results
//   rollback;
//
// so it runs against the linked (live) database and leaves it untouched. The
// last statement before rollback selects the results; the first row is the
// SUMMARY line. The cycles files are re-run too: their cycles are moved out of
// the way by then (see the persona file), so the re-seed must leave them, their
// tiers, rewards and items exactly as they are (T8).
//
// The splice list is the apply order (court-pass-apply.ps1): the xp file, both
// cycles files and the catch-up share one transaction there; the art files
// (generated by art/court-pass/build.mjs <cycle>) are spliced when they exist.
// The catch-up replays the live pickle_ledger since Nov 1 inside this rolled-
// back transaction, taking profile rows FOR UPDATE. So the unapplied variant
// first takes profiles in EXCLUSIVE mode, as the apply script's step 6 prelude
// does: EXCLUSIVE conflicts with ROW SHARE too (SELECT ... FOR UPDATE, FK
// checks), so the LOCK waits out every transaction holding a profile row lock
// and none can start until the rollback; plain SELECTs still run. (The tables
// file's CREATE TRIGGER on profiles takes only SHARE ROW EXCLUSIVE, which lets
// a live FOR UPDATE through and can deadlock with the replay.) It holds every
// profile write (match saves, logins, edits) and, from the tables file's ADD
// COLUMN, every home_items read until the rollback: run it at a quiet hour.
//
//   node supabase/tests/build-court-pass-test.mjs [out.sql]
//   node supabase/tests/build-court-pass-test.mjs --applied [out.sql]
//     (the files are already live: inline none of them, test what is there)
//   (from the linked checkout) supabase db query --linked -f <out.sql> -o csv
//
// Refuses to build if any input holds a top-level transaction statement
// (begin; / commit; / end; / rollback;), which would end the rolled-back
// transaction early and apply the rest for real, and checks the output starts
// with "begin;" and ends with "rollback;". A missing input fails with its name.
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const supa = path.resolve(here, '..');

const args = process.argv.slice(2);
const applied = args.includes('--applied');
const outArg = args.find((a) => a !== '--applied');

const ART = ['migration_court_pass_art_2026_11.sql', 'migration_court_pass_art_2026_12.sql'];
const art = ART.filter((f) => fs.existsSync(path.join(supa, f)));
export const MIGRATIONS = [
  'migration_court_pass_tables.sql',
  'migration_court_pass_xp.sql',
  'migration_court_pass_cycles_2026_11.sql',
  'migration_court_pass_cycles_2026_12_2027_01.sql',
  'court_pass_catchup_2026_11.sql',
  ...art,
];
const HARDENING = 'migration_rls_hardening_2026q3.sql';
export const RERUN = [...MIGRATIONS, HARDENING];
const BODY = path.join(here, 'court_pass_personas.sql');
const MIGRATIONS_MARKER = '-- @@MIGRATIONS@@';
const RERUN_MARKER = '-- @@RERUN@@';

/** The SQL with comments, string literals and dollar-quoted bodies blanked out. */
function topLevel(sql) {
  let out = '';
  let i = 0;
  while (i < sql.length) {
    const rest = sql.slice(i);
    if (rest.startsWith('--')) {
      const nl = sql.indexOf('\n', i);
      i = nl < 0 ? sql.length : nl;
      continue;
    }
    if (rest.startsWith('/*')) {
      const close = sql.indexOf('*/', i + 2);
      i = close < 0 ? sql.length : close + 2;
      continue;
    }
    const tag = rest.match(/^\$[A-Za-z_]*\$/);
    if (tag) {
      const close = sql.indexOf(tag[0], i + tag[0].length);
      i = close < 0 ? sql.length : close + tag[0].length;
      out += ' ';
      continue;
    }
    if (sql[i] === "'") {
      let j = i + 1;
      while (j < sql.length && !(sql[j] === "'" && sql[j + 1] !== "'")) j += sql[j] === "'" ? 2 : 1;
      i = j + 1;
      out += ' ';
      continue;
    }
    out += sql[i];
    i += 1;
  }
  return out;
}

function fail(msg) {
  console.error(`FAILED: ${msg}`);
  process.exit(1);
}

function guard(name, sql) {
  const bad = topLevel(sql).match(/(^|;)\s*(begin|commit|end|rollback|abort|start\s+transaction)\s*(;|$)/im);
  if (bad) fail(`${name} contains a top-level "${bad[2]}" statement; it would end the test transaction.`);
  return sql;
}

function read(file) {
  if (!fs.existsSync(file)) fail(`${path.relative(supa, file)} is missing (looked in ${path.dirname(file)}).`);
  return guard(path.basename(file), fs.readFileSync(file, 'utf8').replace(/^﻿/, '').replace(/\r\n/g, '\n'));
}

const body = read(BODY);
// Whole lines only: the header mentions the markers inside other text.
const lineAt = (marker) => {
  const m = new RegExp(`^${marker}$`, 'm').exec(body);
  return m ? m.index : -1;
};
const at = lineAt(MIGRATIONS_MARKER);
const rerunAt = lineAt(RERUN_MARKER);
if (at < 0) fail(`${path.basename(BODY)} has no "${MIGRATIONS_MARKER}" line.`);
if (rerunAt < at) fail(`${path.basename(BODY)} needs "${RERUN_MARKER}" after "${MIGRATIONS_MARKER}".`);
for (const f of ART) {
  if (!applied && !art.includes(f)) console.error(`note: no ${f} yet (art/court-pass/build.mjs generates it); testing without it.`);
}

const migrationSql = (files, label) =>
  applied
    ? [`-- ==== (--applied: the Court Pass files are already live)${label} ====`]
    : files.map((f) => `-- ==== ${f}${label} ====\n${read(path.join(supa, f))}`);

const parts = [
  'begin;',
  "set local lock_timeout = '10s';",
  'set local check_function_bodies = off;',
  ...(applied ? [] : ['lock table public.profiles in exclusive mode;']),
  // --applied runs against the live tables: T11 skips its "XP broken" check,
  // whose ALTER TABLE would hold ACCESS EXCLUSIVE on reward_track_xp_events
  // (every live earn and screen open) until the rollback.
  ...(applied ? ["set local pickleague.cp_test_applied = 'on';"] : []),
  body.slice(0, at),
  ...migrationSql(MIGRATIONS, ''),
  body.slice(at + MIGRATIONS_MARKER.length, rerunAt),
  ...migrationSql(RERUN, ' (re-run)'),
  body.slice(rerunAt + RERUN_MARKER.length).trimEnd(),
  'rollback;',
];

const sql = parts.join('\n') + '\n';
const lines = sql.trimEnd().split('\n');
if (lines[0] !== 'begin;' || lines[lines.length - 1] !== 'rollback;') {
  fail('the output must start with "begin;" and end with "rollback;".');
}

const out = path.resolve(outArg ?? path.join(os.tmpdir(), 'court_pass_test.sql'));
fs.writeFileSync(out, sql);
console.log(out);
