#!/usr/bin/env node
// Regenerates supabase/migration_my_place_items.sql from catalog.json + svg/.
//
//   node art/my-place/build.mjs            (from the repo root, or anywhere)
//
// Every SVG goes through the kit's tools/room-art/import.mjs (sanitize +
// normalize to a viewBox 100 wide; KIT_DIR overrides where the kit is, default
// ../expo-foundation next to this repo), the slot list and the default layout
// are checked with the kit's own validateSlots / validateLayout, and the file
// is refused if anything is off. Review the diff, then apply it yourself.
import { writeFileSync, readdirSync } from 'node:fs';
import { createRequire } from 'node:module';
import { join, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';

const require = createRequire(import.meta.url);
const lib = require('./lib.cjs');
const { loadRoomKit } = await import(pathToFileURL(join(lib.KIT, 'tools', 'room-art', '_load.mjs')).href);
const { layout: L } = loadRoomKit();

const OUT = resolve(lib.HERE, '..', '..', 'supabase', 'migration_my_place_items.sql');
const fail = (m) => {
  console.error(`FAILED: ${m}`);
  process.exit(1);
};

console.log('Step 1: check the catalog');
const cat = lib.catalog();
const fitsKnown = new Set(lib.SERVER_SLOTS.map((s) => s.fits));
const ids = new Set();
for (const it of cat.items) {
  if (!/^[a-z0-9_]{1,64}$/.test(it.id)) fail(`item id "${it.id}" must be 1 to 64 of a-z, 0-9, _.`);
  if (it.id.startsWith('ph_')) fail(`item id "${it.id}" starts with ph_, the retired placeholders' prefix.`);
  if (ids.has(it.id)) fail(`item id "${it.id}" is listed twice.`);
  ids.add(it.id);
  if (!fitsKnown.has(it.fits) || it.fits === 'avatar') fail(`${it.id}: fits "${it.fits}" is no decor slot group in home_slots.`);
  if (!Number.isInteger(it.cost) || it.cost < 0) fail(`${it.id}: cost must be a whole number, 0 or more.`);
  if (!['common', 'rare', 'legendary'].includes(it.rarity)) fail(`${it.id}: rarity "${it.rarity}".`);
  if (it.is_starter && it.cost !== 0) fail(`${it.id}: a starter must cost 0.`);
}
const files = readdirSync(join(lib.HERE, 'svg')).filter((f) => f.endsWith('.svg')).map((f) => f.slice(0, -4));
const extra = files.filter((f) => !ids.has(f));
if (extra.length) fail(`svg/ has art with no catalog item: ${extra.join(', ')}.`);
console.log(`  ${cat.items.length} items, ${cat.items.filter((i) => i.is_starter).length} starters`);

console.log('Step 2: check the slots and the default layout with the kit');
const slots = lib.slotDefs(cat);
const sp = L.validateSlots(slots);
if (sp.length) fail('slots: ' + sp.join(' '));
const layout = lib.defaultLayout(cat);
const lp = L.validateLayout(slots, layout);
if (lp.length) fail('layout: ' + lp.join(' '));
for (const s of slots) if (s.kind !== 'backdrop' && !layout.placements[s.id]) fail(`layout has no placement for ${s.id}.`);
for (const k of Object.keys(layout.placements)) if (!slots.find((s) => s.id === k && s.kind !== 'backdrop')) fail(`layout places "${k}", which is no boxed slot.`);

console.log('Step 3: import every SVG with import.mjs');
const rows = cat.items.map((it) => {
  const a = lib.importArt(it);
  if (a.svg.includes('$svg$')) fail(`${it.id}: the art contains "$svg$", which would end the SQL quote.`);
  if (Math.abs(a.aspect - it.aspect) > 0.01) fail(`${it.id}: art aspect ${a.aspect} is not the catalog's ${it.aspect}.`);
  return { it, ...a };
});
console.log(`  ${rows.length} imported, ${rows.reduce((n, r) => n + r.svg.length, 0).toLocaleString()} characters of art`);

const q = (v) => (v == null ? 'null' : `'${String(v).replace(/'/g, "''")}'`);
const layoutJson = JSON.stringify(layout);
if (layoutJson.includes('$layout$')) fail('layout contains "$layout$".');

const itemValues = rows
  .map(({ it, aspect }) =>
    `  (${[q(it.id), q(it.name), q(it.fits), it.cost, q(it.rarity), 'null', 'null', 'null', 'null', aspect, q(it.icon), it.sort, it.is_starter].join(', ')})`,
  )
  .join(',\n');
const artValues = rows.map(({ it, svg }) => `  (${q(it.id)}, $svg$${svg}$svg$)`).join(',\n');
const starters = cat.items.filter((i) => i.is_starter).map((i) => i.id);

const sql = `-- ============================================================
-- My Place, phase 3: the real decor catalog (${rows.length} items) and the default layout.
--
-- GENERATED by art/my-place/build.mjs from art/my-place/catalog.json and
-- art/my-place/svg/*.svg (each run through expo-foundation's
-- tools/room-art/import.mjs: sanitized, normalized to a viewBox 100 wide).
-- Do not edit by hand: change the catalog or the art, then re-run the build.
--
-- 1. Retires the phase 2 placeholders (ids ph_*): available_until = now(),
--    is_starter = false. Never a delete: home_owned_items / home_equipped
--    reference items on delete restrict. A re-run keeps the first retire time.
-- 2. Upserts the real items into home_items. On a re-run: name, slot_group,
--    cost, rarity, art_aspect, icon and sort follow the catalog; season,
--    available_from and available_until are left alone (so an item retired
--    later stays retired), and a retired item never turns back into a starter.
-- 3. Upserts their art into home_item_art (updated_at moves only when the
--    SVG changed).
-- 4. room_layout 'default' gets the catalog's defaultLayout only while it has
--    no placements: a layout the admin saved is never overwritten.
--
-- Starters (free, given once by claim_my_place_starter): ${starters.join(', ')}.
--
-- Idempotent; no top-level transaction. Row locks on home_items,
-- home_item_art and room_layout only. Apply after migration_my_place.sql:
--   supabase db query --linked -f supabase/migration_my_place_items.sql
-- Check (rolled back): node supabase/tests/build-my-place-items-test.mjs <out.sql>
--   then supabase db query --linked -f <out.sql> -o csv
-- ============================================================

-- ── 1. Retire the placeholders ───────────────────────────────────────────
update public.home_items
   set available_until = least(coalesce(available_until, now()), now()),
       is_starter = false
 where id like 'ph\\_%'
   and (is_starter or available_until is null or available_until > now());

-- ── 2. The catalog ───────────────────────────────────────────────────────
insert into public.home_items (id, name, slot_group, cost, rarity, season, available_from, available_until, art_key, art_aspect, icon, sort, is_starter) values
${itemValues}
on conflict (id) do update
  set name       = excluded.name,
      slot_group = excluded.slot_group,
      cost       = excluded.cost,
      rarity     = excluded.rarity,
      art_aspect = excluded.art_aspect,
      icon       = excluded.icon,
      sort       = excluded.sort,
      is_starter = excluded.is_starter
                   and (public.home_items.available_until is null or public.home_items.available_until > now());

-- ── 3. The art ───────────────────────────────────────────────────────────
insert into public.home_item_art (item_id, art_svg) values
${artValues}
on conflict (item_id) do update
  set art_svg = excluded.art_svg, updated_at = now()
  where public.home_item_art.art_svg is distinct from excluded.art_svg;

-- ── 4. The default layout (only while nobody has saved one) ──────────────
insert into public.room_layout (id, layout) values ('default', $layout$${layoutJson}$layout$::jsonb)
on conflict (id) do update
  set layout = excluded.layout, updated_at = now()
  where coalesce(public.room_layout.layout -> 'placements', '{}'::jsonb) = '{}'::jsonb;

notify pgrst, 'reload schema';
`;

console.log('Step 4: write the SQL');
writeFileSync(OUT, sql);
console.log(`wrote ${OUT} (${sql.length.toLocaleString()} characters)`);
